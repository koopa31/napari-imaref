import numpy as np
import numpy.random as npr

def recaler_points(px, py, pz, shape=(211, 512, 512), scale=30, bruit=0.1, seed=None):
    """
    Recale les points d'une ellipsoïde simulée dans un volume image et ajoute un bruit aléatoire.

    Paramètres :
    - px, py, pz : coordonnées initiales des points (X, Y, Z)
    - shape : taille de l'image (Z, Y, X)
    - scale : facteur d'échelle appliqué aux coordonnées
    - bruit : intensité du bruit aléatoire ajouté (en unités après scaling)
    - seed : entier pour reproductibilité (optionnel)

    Retour :
    - points_recalés : array (n, 3) en Z, Y, X
    """
    if seed is not None:
        npr.seed(seed)

    center = np.array([shape[0] // 2, shape[1] // 2, shape[2] // 2])  # (Z, Y, X)

    points = np.stack([pz, py, px], axis=1)  # (n, 3) en ZYX
    points_scaled = points * scale

    # Bruit aléatoire indépendant pour chaque coordonnée
    perturb = bruit * npr.randn(*points_scaled.shape)
    points_noisy = points_scaled + perturb

    # Translation vers le centre de l'image
    points_translated = points_noisy + center

    return points_translated  # (n, 3)


